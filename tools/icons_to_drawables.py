"""Turns icons/moment/<IconId>.svg into app/src/main/res/drawable/moment_icon_<IconId>.xml,
and writes the IconId table the app reads them through (ui/MomentIcons.kt).

The SVGs are the source: edit or add one, then run `python tools/icons_to_drawables.py`
from the repository root. Only the SVG subset the icons use is understood: a 24x24
viewBox, stroke attributes on the <svg> element, and <path> elements, each optionally
with fill="currentColor" to draw it filled. Icon() tints the result, so the colours
written here don't matter.
"""
import glob
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "icons", "moment")
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
KOTLIN = os.path.join(ROOT, "app", "src", "main", "java", "dev", "wiserlocal", "app", "ui", "MomentIcons.kt")
NS = "{http://www.w3.org/2000/svg}"


def convert(path):
    svg = ET.parse(path).getroot()
    if svg.get("viewBox") != "0 0 24 24":
        raise SystemExit(f"{path}: viewBox must be 0 0 24 24")
    width = svg.get("stroke-width", "1.75")
    cap = svg.get("stroke-linecap", "round")
    join = svg.get("stroke-linejoin", "round")
    title = svg.find(NS + "title")
    lines = ['<?xml version="1.0" encoding="utf-8"?>']
    if title is not None:
        lines.append(f"<!-- {title.text}. Generated from icons/moment by tools/icons_to_drawables.py -->")
    lines += [
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for p in svg.iter(NS + "path"):
        d = re.sub(r"\s+", " ", p.get("d")).strip()
        if p.get("fill", "none") != "none":
            lines.append(f'    <path android:fillColor="#FF000000" android:pathData="{d}"/>')
        else:
            lines.append(
                f'    <path android:strokeColor="#FF000000" android:strokeWidth="{width}"'
                f' android:strokeLineCap="{cap}" android:strokeLineJoin="{join}"'
                f' android:pathData="{d}"/>'
            )
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    icons = {}
    for path in glob.glob(os.path.join(SRC, "*.svg")):
        name = os.path.splitext(os.path.basename(path))[0]
        if not name.isdigit():
            raise SystemExit(f"{path}: name it after its IconId, like 12.svg")
        with open(os.path.join(OUT, f"moment_icon_{name}.xml"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(convert(path))
        title = ET.parse(path).getroot().find(NS + "title")
        icons[int(name)] = title.text if title is not None else f"Icon {name}"
    rows = "\n".join(
        f'    {i} to MomentIcon(R.drawable.moment_icon_{i}, "{icons[i]}"),' for i in sorted(icons)
    )
    with open(KOTLIN, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(KOTLIN_FILE.format(rows=rows))
    print(f"Wrote {len(icons)} drawables and MomentIcons.kt; IconIds {min(icons)}..{max(icons)}")


KOTLIN_FILE = """\
// Generated by tools/icons_to_drawables.py from icons/moment: edit the SVGs, not this file.
package dev.wiserlocal.app.ui

import androidx.annotation.DrawableRes
import dev.wiserlocal.app.R

class MomentIcon(@DrawableRes val drawable: Int, val name: String)

/** The icons Moments and automations can have, by the hub's IconId. */
val MOMENT_ICONS: Map<Int, MomentIcon> = linkedMapOf(
{rows}
)
"""


if __name__ == "__main__":
    main()
